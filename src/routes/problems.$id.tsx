import { createFileRoute, Link } from "@tanstack/react-router";
import { useState } from "react";
import { useI18n } from "@/lib/i18n";
import { addReply, allProblems, cycleStep, progressOf, useStore } from "@/lib/data";
import { myVote, useExtra } from "@/lib/community";
import { VoteBox } from "@/components/spaces";
import { ProgressBar, SourceBadge, StatusPill } from "@/components/kardaven";

export const Route = createFileRoute("/problems/$id")({
  head: () => ({
    meta: [
      { title: "Problem & Action Plan — KARDAVEN" },
      { name: "description", content: "Discussion, AI summary and action plan for a problem on KARDAVEN." },
      { property: "og:title", content: "Problem & Action Plan — KARDAVEN" },
      { property: "og:description", content: "See replies, the AI summary and the step-by-step plan." },
      { property: "og:type", content: "article" },
      { name: "twitter:card", content: "summary" },
    ],
  }),
  component: Detail,
});

function Detail() {
  const { id } = Route.useParams();
  const { t, lang } = useI18n();
  const fr = lang === "fr";
  const st = useStore();
  const x = useExtra();
  const p = allProblems(st).find((x) => x.id === id);
  const [reply, setReply] = useState("");

  if (!p) return <div className="px-5 py-20 text-center text-muted-foreground">…<br /><Link to="/problems" className="text-electric">{t("back")}</Link></div>;
  const pct = progressOf(p);
  // Quora-style: answers rise with votes; verified experience breaks ties.
  const score = (rid: string) => myVote(x, `problem/${p.id}/${rid}`);
  const sorted = [...p.replies].sort((a, b) => score(b.id) - score(a.id) || Number(b.verified ?? false) - Number(a.verified ?? false));
  const bestId = sorted.length && score(sorted[0]!.id) > 0 ? sorted[0]!.id : null;

  return (
    <div className="mx-auto max-w-3xl px-5 py-6">
      <Link to="/problems" className="text-sm text-muted-foreground">← {t("back")}</Link>
      <div className="mt-4 flex flex-wrap items-center gap-2">
        <span className="eyebrow text-electric">{p.category}</span><SourceBadge isDemo={p.isDemo} />
        {p.verified && <span className="eyebrow !text-[9px] text-gold">✦ {t("verified")}</span>}
      </div>
      <h1 className="mt-2 font-sans text-2xl font-bold leading-tight">{p.title}</h1>
      <p className="mt-1 text-xs text-muted-foreground">{p.author} · {p.at}</p>
      {p.isDemo && <p className="mt-3 rounded-lg border border-border px-3 py-2 text-xs text-muted-foreground">{t("demo_note")}</p>}
      <p className="mt-4 text-foreground/90">{p.description}</p>

      <dl className="mt-4 grid gap-2 text-sm">
        {([["goal", p.goal], ["constraints", p.constraints], ["tried", p.tried]] as const).filter(([, v]) => v).map(([k, v]) => (
          <div key={k} className="rounded-xl bg-muted/40 px-3 py-2.5"><dt className="eyebrow text-gold">{t(k)}</dt><dd className="mt-1">{v}</dd></div>
        ))}
      </dl>

      <section className="mt-6 rounded-2xl glass ai-border p-4">
        <div className="flex items-center gap-2">
          <span className="h-2 w-2 rounded-full bg-electric animate-pulse-glow" />
          <h2 className="eyebrow text-electric">{t("ai_summary")}</h2>
        </div>
        {p.ai && <p className="eyebrow mt-3 !text-[10px] text-gold">{fr ? "Diagnostic" : "Diagnosis"}</p>}
        <p className="mt-2 text-sm leading-relaxed">{p.aiSummary}</p>
        {p.ai ? (
          <div className="mt-4 space-y-3 text-sm">
            {p.ai.pitfalls.length > 0 && <div><p className="eyebrow !text-[10px] text-gold">{fr ? "Pièges à éviter" : "Pitfalls to avoid"}</p><ul className="mt-1 list-disc space-y-1 pl-5">{p.ai.pitfalls.map((x, i) => <li key={i}>{x}</li>)}</ul></div>}
            {p.ai.resources.length > 0 && <div><p className="eyebrow !text-[10px] text-gold">{fr ? "Ressources recommandées" : "Recommended resources"}</p><ul className="mt-1 list-disc space-y-1 pl-5">{p.ai.resources.map((x, i) => <li key={i}>{x}</li>)}</ul></div>}
            {p.ai.eta && <p><span className="eyebrow !text-[10px] text-gold">{fr ? "Temps estimé" : "Estimated time"}</span> · {p.ai.eta}</p>}
            <p className="text-[11px] text-muted-foreground">{fr ? "Analyse générée par Kardaven (IA) — à vérifier selon votre contexte." : "Generated by Kardaven (AI) — check against your context."}</p>
          </div>
        ) : <p className="mt-3 text-[11px] text-muted-foreground">⚠ {t("ai_simulated")}</p>}
      </section>

      <section className="mt-6 rounded-2xl glass p-4">
        <div className="flex items-baseline justify-between">
          <h2 className="font-sans text-lg font-semibold">{t("plan")}</h2>
          <span className="font-display text-xl text-gradient-gold">{pct}%</span>
        </div>
        <div className="mt-2"><ProgressBar value={pct} /></div>
        <p className="mt-2 text-xs text-muted-foreground">{t("tap_status")}</p>
        <ol className="mt-3 space-y-2">
          {p.steps.map((s, i) => (
            <li key={s.id}>
              <button onClick={() => cycleStep(p.id, s.id)} className="flex w-full items-center gap-3 rounded-xl bg-muted/50 px-3 py-3 text-left text-sm transition active:scale-[.99]">
                <span className={`grid h-6 w-6 shrink-0 place-items-center rounded-full border font-mono text-[10px] ${s.status === "done" ? "border-success bg-success/20 text-success" : "border-border"}`}>{s.status === "done" ? "✓" : i + 1}</span>
                <span className={`flex-1 ${s.status === "done" ? "text-muted-foreground line-through" : ""}`}>{s.text}</span>
                <StatusPill status={s.status} />
              </button>
            </li>
          ))}
        </ol>
      </section>

      <section className="mt-6 pb-6">
        <h2 className="font-sans text-lg font-semibold">{p.replies.length} {t("replies")}</h2>
        <div className="mt-3 space-y-3">
          {sorted.map((r) => (
            <div key={r.id} className={`rounded-2xl border p-4 ${r.id === bestId ? "border-success/50" : r.verified ? "border-gold/40 glow-gold" : "border-border"}`}>
              <div className="flex items-center gap-2 text-xs">
                <span className="font-semibold">{r.author}</span><SourceBadge isDemo={r.isDemo} />
                {r.verified && <span className="eyebrow !text-[9px] text-gold">✦ {t("verified")}</span>}
                {r.id === bestId && <span className="rounded-full bg-success/15 px-2 py-0.5 text-[10px] font-semibold text-success">★ {t("best_answer")}</span>}
                <span className="ml-auto text-muted-foreground">{r.at}</span>
              </div>
              <p className="mt-2 text-sm">{r.body}</p>
              <div className="mt-2"><VoteBox row k={`problem/${p.id}/${r.id}`} base={0} /></div>
            </div>
          ))}
        </div>
        <form onSubmit={(e) => { e.preventDefault(); if (reply.trim()) { addReply(p.id, reply.trim()); setReply(""); } }} className="mt-4">
          <textarea value={reply} onChange={(e) => setReply(e.target.value)} rows={3} placeholder={t("reply_ph")}
            className="w-full rounded-xl border border-input bg-muted/40 px-3.5 py-3 text-base outline-none focus:border-electric" />
          <button className="mt-2 w-full rounded-xl border border-gold/50 py-3 font-semibold text-gold transition active:scale-[.98]">{t("post_reply")}</button>
          <p className="mt-2 text-center text-[11px] text-muted-foreground">{t("local_note")}</p>
        </form>
      </section>
    </div>
  );
}
